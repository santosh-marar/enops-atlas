import type {
  CanonicalColumn,
  CanonicalSchema,
  CanonicalTable,
  ColumnDefault,
  IndexElement,
} from "@enops/atlas-schema";
import { assertSupported, nativeParts } from "./capabilities";

function quote(identifier: string): string {
  return `"${identifier.replaceAll('"', '""')}"`;
}
function qualify(schema: string, name: string): string {
  return `${quote(schema)}.${quote(name)}`;
}
function sqlType(column: CanonicalColumn): string {
  if (column.type === "enum")
    return qualify(column.enumSchema ?? "public", column.enumName!);
  if (column.nativeType) {
    const { name, args } = nativeParts(column);
    return args && name.startsWith("timestamp ")
      ? name.replace("timestamp", `timestamp(${args})`)
      : `${name}${args ? `(${args})` : ""}`;
  }
  switch (column.type) {
    case "string":
      return column.length ? `varchar(${column.length})` : "varchar";
    case "int":
      return "integer";
    case "float":
      return "double precision";
    case "decimal":
      return column.precision
        ? `numeric(${column.precision.join(", ")})`
        : "numeric";
    case "unsupported":
      throw new Error("Missing verified native type");
    default:
      return column.type;
  }
}
function renderDefault(value: ColumnDefault): string {
  switch (value.type) {
    case "string":
      return `'${String(value.value).replaceAll("'", "''")}'`;
    case "number":
      return value.literal ?? String(value.value);
    case "boolean":
      return value.value ? "TRUE" : "FALSE";
    case "expression":
      return `(${String(value.value)})`;
    case "null":
      return "NULL";
  }
}
function elements(index: {
  columns: string[];
  elements?: IndexElement[];
}): string {
  return (
    index.elements ?? index.columns.map((value) => ({ kind: "column", value }))
  )
    .map((e) => (e.kind === "column" ? quote(e.value) : `(${e.value})`))
    .join(", ");
}
function check(check: { name: string | null; expression: string }): string {
  return `${check.name ? `CONSTRAINT ${quote(check.name)} ` : ""}CHECK (${check.expression})`;
}
function tableDdl(table: CanonicalTable): string {
  const lines = table.columns.map((column) => {
    const parts = [quote(column.name), sqlType(column)];
    if (column.autoIncrement) parts.push("GENERATED BY DEFAULT AS IDENTITY");
    if (!column.nullable || table.primaryKey?.columns.includes(column.name))
      parts.push("NOT NULL");
    if (column.default) parts.push(`DEFAULT ${renderDefault(column.default)}`);
    if (column.unique) parts.push("UNIQUE");
    for (const constraint of column.checks ?? []) parts.push(check(constraint));
    return parts.join(" ");
  });
  if (table.primaryKey)
    lines.push(
      `CONSTRAINT ${quote(table.primaryKey.name ?? `${table.name}_pkey`)} PRIMARY KEY (${table.primaryKey.columns.map(quote).join(", ")})`
    );
  for (const unique of table.uniqueConstraints) {
    if (unique.elements?.some((e) => e.kind === "expression")) continue;
    lines.push(
      `CONSTRAINT ${quote(unique.name ?? `${table.name}_${unique.columns.join("_")}_key`)} UNIQUE (${elements(unique)})`
    );
  }
  for (const constraint of table.checks ?? []) lines.push(check(constraint));
  return `CREATE TABLE ${qualify(table.schema, table.name)} (\n  ${lines.join(",\n  ")}\n);`;
}
export function generatePostgresSql(schema: CanonicalSchema): string {
  assertSupported(schema, "sql");
  const statements: string[] = [];
  const spaces = new Set([
    ...schema.tables.map((t) => t.schema),
    ...schema.enums.map((e) => e.schema),
  ]);
  for (const space of [...spaces].sort())
    if (space !== "public")
      statements.push(`CREATE SCHEMA IF NOT EXISTS ${quote(space)};`);
  for (const enumeration of schema.enums)
    statements.push(
      `CREATE TYPE ${qualify(enumeration.schema, enumeration.name)} AS ENUM (${enumeration.values.map((v) => `'${v.replaceAll("'", "''")}'`).join(", ")});`
    );
  for (const table of schema.tables) statements.push(tableDdl(table));
  // All tables exist before relationships are added, including cycles and forward references.
  for (const table of schema.tables)
    for (const fk of table.foreignKeys) {
      const clauses = [
        `ALTER TABLE ${qualify(table.schema, table.name)} ADD CONSTRAINT ${quote(fk.name ?? `${table.name}_${fk.columns.join("_")}_fkey`)} FOREIGN KEY (${fk.columns.map(quote).join(", ")}) REFERENCES ${qualify(fk.refTable.schema, fk.refTable.table)} (${fk.refColumns.map(quote).join(", ")})`,
      ];
      if (fk.onDelete !== "none")
        clauses.push(`ON DELETE ${fk.onDelete.toUpperCase()}`);
      if (fk.onUpdate !== "none")
        clauses.push(`ON UPDATE ${fk.onUpdate.toUpperCase()}`);
      statements.push(`${clauses.join(" ")};`);
    }
  for (const table of schema.tables)
    for (const index of [
      ...table.indexes,
      ...table.uniqueConstraints.filter((u) =>
        u.elements?.some((e) => e.kind === "expression")
      ),
    ]) {
      const unique = table.uniqueConstraints.some(
        (constraint) => constraint === index
      );
      const name =
        index.name ??
        `${table.name}_${statements.length}_${unique ? "key" : "idx"}`;
      const method = index.type ? ` USING ${index.type}` : "";
      statements.push(
        `CREATE ${unique ? "UNIQUE " : ""}INDEX ${quote(name)} ON ${qualify(table.schema, table.name)}${method} (${elements(index)});`
      );
    }
  return `${statements.join("\n\n")}\n`;
}
